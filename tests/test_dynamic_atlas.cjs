"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'../site');
const paths=require(path.join(base,'atlas-paths.js'));
const expanded=require(path.join(base,'atlas-expansion.js'));
const specialist=require(path.join(base,'atlas-specialist.js'));
const depthA=require(path.join(base,'atlas-depth-a.js'));
const depthB=require(path.join(base,'atlas-depth-b.js'));
const depthC=require(path.join(base,'atlas-depth-c.js'));
const depthD=require(path.join(base,'atlas-depth-d.js'));
const ai=require(path.join(base,'atlas-ai.js'));
const regional=require(path.join(base,'atlas-regional.js'));
const everyday=require(path.join(base,'atlas-everyday.js'));
const regionalExt=require(path.join(base,'atlas-regional-ext.js'));
const everydayExt=require(path.join(base,'atlas-everyday-ext.js'));
const popularLinks=require(path.join(base,'atlas-popular-links.js'));
const catalog=require(path.join(base,'atlas-catalog-core.js'));
const gate=require(path.join(base,'link-gate.js'));
const current=catalog.catalog();
const staticTotal=catalog.base.length+catalog.extras.length+paths.links.length+expanded.links.length+specialist.links.length+depthA.links.length+depthB.links.length+depthC.links.length+depthD.links.length+ai.links.length+regional.links.length+everyday.links.length+regionalExt.links.length+everydayExt.links.length+popularLinks.links.length;
assert.ok(expanded.links.length>=80,'expanded resources must be significant');
assert.equal(current.length,staticTotal,'catalog data must be actually merged and deduplicated');
assert.equal(current.length,1239+popularLinks.links.length,'expanded directory must include all curated depths');
assert.equal(new Set(current.map(x=>x.url)).size,current.length,'all static URLs unique');
for(const x of current){
 assert.ok(x.name&&x.category&&x.description);
 assert.ok(catalog.validURL(x.url));
 assert.equal(gate.urlRisk(x.url).blocked,false,'unsafe entry: '+x.name);
}
const extra={name:'新增后台网址',url:'https://example-directory-addition.example/',category:'其他',description:'后台新增数据的测试夹具'};
const existing={name:'后台更新过的 GitHub',url:'https://github.com/',category:'开发',description:'模拟管理员改名'};
const merged=catalog.catalog([existing,extra]);
assert.equal(merged.length,current.length+1,'new backend records must change the number dynamically');
assert.equal(merged.find(x=>x.url==='https://github.com/').name,existing.name,'backend entry takes priority');
assert.equal(catalog.catalog([existing,existing]).length,current.length,'duplicate backend URL does not inflate count');
const home=fs.readFileSync(path.join(base,'index.html'),'utf8');
const directory=fs.readFileSync(path.join(base,'directory.html'),'utf8');
const directoryJS=fs.readFileSync(path.join(base,'directory.js'),'utf8');
const homeJS=fs.readFileSync(path.join(base,'atlas-summary.js'),'utf8');
const feedback=fs.readFileSync(path.join(base,'feedback.php'),'utf8');
const localPref=fs.readFileSync(path.join(base,'feedback-pref.js'),'utf8');
assert.ok(home.includes('data-aq-catalog-summary'), 'homepage count must be populated by JS');
assert.ok(homeJS.includes('catalog.load()'),'homepage count must include backend data');
assert.ok(directoryJS.includes('catalog.load()'),'directory count must include backend data');
assert.ok(directoryJS.includes('records.length'),'directory must describe real in-memory count');
assert.ok(directoryJS.includes('limit=filtered().length'),'user must be able to display the entire catalog');
assert.ok(directory.includes('id="atlasShowAll"'));
assert.ok(directory.includes('id="atlasNoMatchDialog"'));
assert.ok(directoryJS.includes("submitSearch(input.value)") && directoryJS.includes("if(loaded)completeSearch();") && directoryJS.includes("openNoMatch(q)"),'no-match prompt is submitted and only dispatched after catalogue loads');
assert.ok(!directoryJS.includes("input.addEventListener('input',openNoMatch"),'do not pop while typing');
assert.ok(directoryJS.includes('atlasCompareBoard'));
assert.ok(directory.includes('id="atlasRecommendQuery"'));
assert.ok(feedback.includes("$_GET['q']"),'feedback must permit explicit non-collection report');
assert.match(feedback,/feedback-pref\.js\?v=[0-9]+/);
assert.ok(localPref.includes("check.checked"),'contact remembering must be opt-in');
assert.ok(localPref.includes('localStorage.removeItem(KEY)'), 'user needs local forget button');
const savedEntry=localPref.match(/const entry=\{[^}]+\}/)?.[0]||'';
assert.ok(savedEntry && !/\\bbody\\b/.test(savedEntry),'only opt-in contact fields may be persisted');
assert.ok(!localPref.includes('innerHTML'),'never inject visitor text as HTML');
assert.ok(!home.includes('126 个精选入口'));
assert.ok(homeJS.includes('new Set(info.items.map(x=>x.category))'),'homepage category count must be dynamic');
console.log('PASS: dynamic '+current.length+'-URL catalog, backend update/duplicate, show-all, submit-only suggestions and opt-in local feedback');
