"use strict";
const assert=require('node:assert/strict'),client=require('../research/atlas-worker-client.js');
const sent=[],results=[],errors=[];
const w={postMessage(m){sent.push(m)},terminate(){this.terminated=true}};
const c=client.create(w,(urls,q)=>results.push({urls,q}),code=>errors.push(code));
const emit=m=>w.onmessage({data:m});
c.init({}, []);const init=sent[0];
c.query('first');c.query('second');
assert.equal(sent.length,1);
emit({type:'ready',id:init.id,epoch:1});assert.equal(sent[1].query,'second');
c.query('third');c.query('latest');assert.equal(sent.length,2);
emit({type:'result',id:sent[1].id,epoch:1,urls:['old']});assert.equal(results.length,0);assert.equal(sent[2].query,'latest');
emit({type:'result',id:sent[2].id,epoch:1,urls:['new']});assert.deepEqual(results,[{urls:['new'],q:'latest'}]);
c.init({}, []);const secondInit=sent[3];
emit({type:'ready',id:init.id,epoch:1});c.query('after reload');assert.equal(sent.length,4);
emit({type:'ready',id:secondInit.id,epoch:2});assert.equal(sent[4].query,'after reload');
c.close();assert.ok(w.terminated);emit({type:'result',id:sent[4].id,epoch:2,urls:['late']});assert.equal(results.length,1);
console.log('WORKER_CLIENT_PROTOCOL_PASS');
