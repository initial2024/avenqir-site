"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const site=path.resolve(__dirname,'../site');
const window={AVENQIR_I18N:{locale:'en'},addEventListener(){}};
vm.runInNewContext(fs.readFileSync(path.join(site,'aq-copy.js'),'utf8'),{window});
const copy=window.AVENQIR_PAGE_COPY;
assert.ok(copy.originalSize>=350,'at least 350 fixed UI strings translated');
assert.equal(copy.translate('↗ 随机发现'),'↗ Random discovery');
assert.equal(copy.translate('结果排序'),'Sort results');
assert.equal(copy.translate('搜索建议'),'Search suggestions');
assert.equal(copy.translate('隐私说明'),'Privacy policy');
assert.equal(copy.translate('选择地区'),'Choose a region');
assert.equal(copy.translate('即将访问第三方网站'),'Leaving for a third-party site');
assert.equal(copy.translate('没有找到匹配项'),'No matches found');
assert.equal(copy.translate('添加或修改网址'),'Add or edit a bookmark');
assert.equal(copy.translate('换设备操作：'),'Move to a new device:');
window.AVENQIR_I18N.locale='ja';
assert.equal(copy.translate('隐私说明'),'Privacy policy','English fallback rather than Simplified Chinese for unsupported Japanese page copy');
window.AVENQIR_I18N.locale='zh-Hans';
assert.equal(copy.translate('隐私说明'),'隐私说明');
window.AVENQIR_I18N.locale='zh-Hant';
assert.equal(copy.translate('隐私说明'),'隱私說明');
const siteJs=fs.readFileSync(path.join(site,'site.js'),'utf8');
assert.ok(siteJs.includes("script.addEventListener('load'"),'copy pack loads only after locale engine');
assert.ok(siteJs.includes('aq-copy.js?v=25'));
assert.ok(siteJs.includes('aq-i18n.js?v=25'));
const region=fs.readFileSync(path.join(site,'atlas-region-ui.js'),'utf8');
const personalize=fs.readFileSync(path.join(site,'atlas-personalize-ui.js'),'utf8');
const atlas=fs.readFileSync(path.join(site,'directory.js'),'utf8');
const palette=fs.readFileSync(path.join(site,'quick-search.js'),'utf8');
assert.ok(region.includes("new Intl.DisplayNames"),'40 regions use internationalized names without TLD guessing');
for(const js of [region,personalize,atlas,palette]){
 assert.ok(js.includes("aq:language-change"),'dynamic interface must redraw after manually changing locale');
}
assert.ok(atlas.includes('Original description (Chinese)'),'untranslated source descriptions are disclosed');
assert.ok(atlas.includes("renderSafetyAudit()"),'original structural audit retained');
assert.ok(atlas.includes("languageMode()!=='exact'"),'source language matching preserved');
assert.ok(palette.includes('EN_NAMES'),'private command palette has English readable default');
const html=fs.readFileSync(path.join(site,'orbit-bridge.html'),'utf8');
assert.ok(html.includes('id="orbit-no-backend"'));
const sw=fs.readFileSync(path.join(site,'sw.js'),'utf8');
assert.ok(sw.includes("'./aq-copy.js'"));
assert.ok(Number(sw.match(/const CACHE = 'avenqir-v([0-9]+)-static-/)?.[1])>=97,'updated offline cache generation');
const directoryHtml=fs.readFileSync(path.join(site,'directory.html'),'utf8');
assert.ok(directoryHtml.includes('aq-i18n.js?v=26'));
assert.ok(directoryHtml.includes('aq-copy.js?v=26'));
assert.ok(directoryHtml.includes('atlas-region-ui.js?v=30'));
assert.ok(directoryHtml.includes('atlas-personalize-ui.js?v=29'));
assert.ok(directoryHtml.indexOf('aq-i18n.js?v=26')<directoryHtml.search(/directory\.js\?v=[0-9]+/),'locale engine loads before directory logic');
assert.ok(!atlas.includes("reviewed?'官方来源已核对 · 非安全认证'"),'dynamic source badge must use locale-aware copy');
assert.ok(!atlas.includes("?'来源已核对':'来源未核对'"),'comparison summary must use locale-aware source labels');
assert.ok(!fs.readFileSync(path.join(site,'aq-copy.js'),'utf8').includes('fetch('));
console.log('PASS: English fallback for 200+ fixed interface labels, locale switch redraw, 40-region internationalized names and no translation data uploads');
